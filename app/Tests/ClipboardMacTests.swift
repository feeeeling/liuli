@MainActor @Test func nativePasteboardPrivacyPauseSearchAndCopy() async throws {
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("liuli-tests-\(UUID())"))
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent("liuli-native-test-\(UUID())")
    let suite = "liuli-native-test-\(UUID())"
    let defaults = try #require(UserDefaults(suiteName: suite))
    defer { pasteboard.releaseGlobally(); defaults.removePersistentDomain(forName: suite); try? FileManager.default.removeItem(at: directory) }
    pasteboard.setString("before startup", forType: .string)
    let history = ClipboardHistory(pasteboard: pasteboard, defaults: defaults, directory: directory, key: Data(repeating: 42, count: 32), monitor: false)
    defer { history.stop() }
    await history.start(); #expect(history.available); #expect(history.count == 0)
    func copy(_ text: String, privacy: String? = nil) {
        let item = NSPasteboardItem(); item.setString(text, forType: .string)
        item.setString("<b>\(text)</b>", forType: .html)
        if let privacy { item.setData(Data([1]), forType: NSPasteboard.PasteboardType(privacy)) }
        pasteboard.clearContents(); pasteboard.writeObjects([item]); history.checkForChanges()
    }
    copy("Alpha 你好 😀"); await history.flush(); #expect(history.count == 1)
    for privacy in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        copy("PRIVATE_SKIP", privacy: privacy); await history.flush(); #expect(history.count == 1)
    }
    history.beginInternalCopy(); copy("internal translation copy"); await history.flush(); history.endInternalCopy()
    #expect(history.count == 1)
    history.setEnabled(false); copy("paused"); await history.flush(); #expect(history.count == 1)
    history.setEnabled(true); history.checkForChanges(); await history.flush(); #expect(history.count == 1)
    copy("Beta result"); await history.flush(); #expect(history.count == 2)
    history.query = "ALPHA 你好"; await history.copySelected()
    #expect(pasteboard.string(forType: .string) == "Alpha 你好 😀")
    #expect(pasteboard.string(forType: .html) == "<b>Alpha 你好 😀</b>")
    history.checkForChanges(); await history.flush(); #expect(history.count == 2)
    history.query = "beta"; await history.copySelected(); #expect(pasteboard.string(forType: .string) == "Beta result")
    await history.removeSelected(); #expect(history.count == 1)
    await history.clear(); #expect(history.count == 0)
}

@MainActor @Test func nativeImageRecordingAndRestoration() async throws {
    let pasteboard = NSPasteboard(name: NSPasteboard.Name("liuli-image-tests-\(UUID())"))
    let directory = FileManager.default.temporaryDirectory.appendingPathComponent("liuli-image-test-\(UUID())")
    let suite = "liuli-image-test-\(UUID())", defaults = try #require(UserDefaults(suiteName: suite))
    defer { pasteboard.releaseGlobally(); defaults.removePersistentDomain(forName: suite); try? FileManager.default.removeItem(at: directory) }
    let history = ClipboardHistory(pasteboard: pasteboard, defaults: defaults, directory: directory, key: Data(repeating: 42, count: 32), monitor: false)
    defer { history.stop() }; await history.start()
    let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
    let image = try Data(contentsOf: root.appendingPathComponent("docs/assets/icon.png"))
    pasteboard.clearContents(); pasteboard.setData(image, forType: .png)
    history.checkForChanges(); await history.flush()
    let record = try #require(history.records.first)
    #expect(record.isImage); #expect(record.width == 256); #expect(record.thumbnail != nil)
    await history.copySelected(); #expect(pasteboard.data(forType: .png) != nil)
    history.stop()
    let reloaded = ClipboardHistory(pasteboard: pasteboard, defaults: defaults, directory: directory, key: Data(repeating: 42, count: 32), monitor: false)
    defer { reloaded.stop() }; await reloaded.start(); #expect(reloaded.count == 1)
}
