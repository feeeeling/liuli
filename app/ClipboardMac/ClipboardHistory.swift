import Security

private enum ClipboardKeychain {
    static func load() throws -> Data {
        let identity: [String: Any] = [kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: "app.liuli.desktop.clipboard", kSecAttrAccount as String: "aes-key-v1"]
        var query = identity
        query[kSecReturnData as String] = true; query[kSecMatchLimit as String] = kSecMatchLimitOne
        query[kSecUseAuthenticationUI as String] = kSecUseAuthenticationUIFail
        var result: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &result)
        if status == errSecSuccess, let data = result as? Data, data.count == 32 { return data }
        guard status == errSecItemNotFound else { throw NSError(domain: NSOSStatusErrorDomain, code: Int(status)) }
        var key = Data(count: 32)
        let randomStatus = key.withUnsafeMutableBytes { SecRandomCopyBytes(kSecRandomDefault, 32, $0.baseAddress!) }
        guard randomStatus == errSecSuccess else { throw NSError(domain: NSOSStatusErrorDomain, code: Int(randomStatus)) }
        var add = identity
        add[kSecValueData as String] = key
        add[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
        let added = SecItemAdd(add as CFDictionary, nil)
        guard added == errSecSuccess else { throw NSError(domain: NSOSStatusErrorDomain, code: Int(added)) }
        return key
    }
}

private enum ClipboardImages {
    static func prepare(_ data: Data) -> (png: Data, thumbnail: Data, width: Int, height: Int)? {
        guard data.count <= 32 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 16384, height <= 16384, width * height <= 33_554_432,
              let image = CGImageSourceCreateImageAtIndex(source, 0, [kCGImageSourceShouldCache: false] as CFDictionary) else { return nil }
        func png(_ image: CGImage) -> Data? {
            let data = NSMutableData()
            guard let destination = CGImageDestinationCreateWithData(data, "public.png" as CFString, 1, nil) else { return nil }
            CGImageDestinationAddImage(destination, image, nil)
            return CGImageDestinationFinalize(destination) ? data as Data : nil
        }
        guard let imageData = png(image), imageData.count <= 8 * 1024 * 1024,
              let small = CGImageSourceCreateThumbnailAtIndex(source, 0, [kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 64, kCGImageSourceCreateThumbnailWithTransform: true] as CFDictionary),
              let thumbnail = png(small) else { return nil }
        return (imageData, thumbnail, width, height)
    }
}

@MainActor @Observable
public final class ClipboardHistory {
    public private(set) var enabled: Bool
    public private(set) var limit: Int
    public private(set) var available = false
    public private(set) var count = 0
    public private(set) var totalMatches = 0
    public private(set) var records: [ClipboardRecord] = []
    public private(set) var error = ""
    public private(set) var usingRecord = false
    public var isVisible = false
    public var selectedID: UUID?
    public var query = "" { didSet { Task { await refresh(reset: true) } } }
    public var onToggle: (() -> Void)?
    public var onDismiss: ((Bool) -> Void)?
    public var onSizeChanged: (() -> Void)?
    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let defaults: UserDefaults
    @ObservationIgnored private let directory: URL
    @ObservationIgnored private let suppliedKey: Data?
    @ObservationIgnored private let monitor: Bool
    @ObservationIgnored private var archive: ClipboardArchive?
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChange: Int
    @ObservationIgnored private var starting = false
    @ObservationIgnored private var suspended = 0
    @ObservationIgnored private var generation = 0
    @ObservationIgnored private var searchGeneration = 0
    @ObservationIgnored private var pendingCapture: Task<Void, Never>?
    private static let excluded = Set(["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])

    public init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard, directory: URL? = nil, key: Data? = nil, monitor: Bool = true) {
        self.pasteboard = pasteboard; self.defaults = defaults; self.suppliedKey = key; self.monitor = monitor
        self.directory = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Liuli/clipboard-history", isDirectory: true)
        self.enabled = defaults.object(forKey: "liuli.clipboard.enabled") as? Bool ?? true
        let stored = defaults.integer(forKey: "liuli.clipboard.limit")
        self.limit = [100, 500, 1000].contains(stored) ? stored : 500
        self.lastChange = pasteboard.changeCount
    }
    public func start() async {
        guard !starting, archive == nil else { return }
        starting = true; defer { starting = false }
        do {
            let key: Data
            if let suppliedKey { key = suppliedKey } else { key = try await Task.detached(priority: .utility) { try ClipboardKeychain.load() }.value }
            let store = try ClipboardArchive(directory: directory, key: key, limit: limit)
            try await store.load(); archive = store; available = true; error = ""
            lastChange = pasteboard.changeCount
            if monitor {
                let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in Task { @MainActor in self?.checkForChanges() } }
                timer.tolerance = 0.1; RunLoop.main.add(timer, forMode: .common); self.timer = timer
            }
            await refresh()
        } catch { self.error = "剪贴板历史暂不可用，请解锁钥匙串后重新开启记录。" }
    }
    public func stop() { timer?.invalidate(); timer = nil }
    public func flush() async { await pendingCapture?.value }
    public func beginInternalCopy() { suspended += 1 }
    public func endInternalCopy() { lastChange = pasteboard.changeCount; suspended = max(0, suspended - 1) }
    public func toggle() { onToggle?() }
    public func dismiss(restore: Bool = true) { onDismiss?(restore) }
    public var status: String { !error.isEmpty ? error : "\(enabled && available ? "正在记录" : enabled ? "正在准备" : "已暂停") · \(count) 条" }
    public func setEnabled(_ value: Bool) {
        enabled = value; generation += 1; lastChange = pasteboard.changeCount
        defaults.set(value, forKey: "liuli.clipboard.enabled")
        if value && archive == nil { Task { await start() } }
    }
    public func setLimit(_ value: Int) {
        guard [100, 500, 1000].contains(value) else { return }
        limit = value; defaults.set(value, forKey: "liuli.clipboard.limit")
        Task { do { try await archive?.configure(limit: value); await refresh() } catch { self.error = "无法更新保留记录数量。" } }
    }
    func checkForChanges() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard enabled, available, suspended == 0, let archive else { return }
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            error = "系统已拒绝剪贴板访问，请在系统设置中允许琉璃读取剪贴板。"; return
        }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.excluded) else { return }
        // Each item can carry its own privacy marker; never merge one into history.
        guard !(pasteboard.pasteboardItems ?? []).contains(where: { !Set($0.types.map(\.rawValue)).isDisjoint(with: Self.excluded) }) else { return }
        var formats: [String: Data] = [:]
        let text = pasteboard.string(forType: .string) ?? ""
        if !text.isEmpty { formats[NSPasteboard.PasteboardType.string.rawValue] = Data(text.utf8) }
        for type in [NSPasteboard.PasteboardType.html, .rtf] {
            if let data = pasteboard.data(forType: type), data.count <= 2 * 1024 * 1024 { formats[type.rawValue] = data }
        }
        let image = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff)
        guard pasteboard.changeCount == change else { return }
        let snapshot = ClipboardSnapshot(formats: formats, text: text, source: NSWorkspace.shared.frontmostApplication?.localizedName ?? "")
        let token = generation, previous = pendingCapture
        pendingCapture = Task { [weak self] in
            await previous?.value
            guard let self, self.enabled, self.generation == token else { return }
            var value = snapshot
            if let image, let prepared = await Task.detached(priority: .utility, operation: { ClipboardImages.prepare(image) }).value {
                value.formats["public.png"] = prepared.png; value.thumbnail = prepared.thumbnail
                value.width = prepared.width; value.height = prepared.height
            }
            guard self.generation == token else { return }
            do { if try await archive.add(value) { self.error = ""; await self.refresh() } }
            catch { self.error = "部分剪贴板记录未能保存。" }
        }
    }
    public func refresh(reset: Bool = false) async {
        searchGeneration += 1; let version = searchGeneration
        guard let result = await archive?.query(query) else { return }
        guard version == searchGeneration else { return }
        let old = reset ? nil : selectedID
        records = result.records; totalMatches = result.total; count = result.count
        selectedID = records.contains(where: { $0.id == old }) ? old : records.first?.id
        onSizeChanged?()
    }
    public func moveSelection(_ delta: Int) {
        let current = records.firstIndex(where: { $0.id == selectedID }) ?? 0
        if !records.isEmpty { selectedID = records[max(0, min(records.count - 1, current + delta))].id }
    }
    public func copySelected(index: Int? = nil) async {
        guard !usingRecord, let archive else { return }
        usingRecord = true; defer { usingRecord = false }
        // Resolve the current query even if Return arrives before the search task.
        await refresh()
        let id: UUID?
        if let index { id = records.indices.contains(index) ? records[index].id : nil } else { id = selectedID }
        guard let id else { return }
        do {
            let formats = try await archive.read(id)
            let item = NSPasteboardItem()
            for (type, data) in formats { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            beginInternalCopy(); defer { endInternalCopy() }
            pasteboard.clearContents()
            guard pasteboard.writeObjects([item]) else { error = "剪贴板暂时被占用，请重试。"; return }
            error = ""; dismiss(); await refresh()
        } catch { error = "这条记录无法读取，可能已被删除。" }
    }
    public func removeSelected() async {
        guard let selectedID else { return }
        do { try await archive?.remove(selectedID); await refresh() } catch { error = "无法删除记录。" }
    }
    public func clear() async {
        generation += 1; await pendingCapture?.value
        do { try await archive?.clear(); await refresh() } catch { error = "无法清空剪贴板历史。" }
    }
}
